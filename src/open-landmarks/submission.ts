/**
 * The metadata of one Open Landmarks submission: `asset.json` and
 * `spatial-source.json`, in the shape their validator and template expect.
 */
import { createHash } from 'node:crypto'
import type { CatalogLandmark } from '../catalog'
import type { Converted } from './convert'
import { parseGlb } from '../glb'
import type { Osm } from './osm'
import type { Reference } from './references'

const R = 6_378_137
const REPOSITORY = 'https://github.com/alexwohlbruck/landmarks'
export const AUTHOR = 'Alex Wohlbruck'

type Ring = Array<[number, number]>
type Polygonal = { type: 'Polygon'; coordinates: Ring[] } | { type: 'MultiPolygon'; coordinates: Ring[][] }

const sha = (b: Uint8Array) => createHash('sha256').update(b).digest('hex')
const round = (v: number, d = 7) => Math.round(v * 10 ** d) / 10 ** d

/** WGS84 ↔ local metres about the anchor: X east, Y north (their Blender frame). */
function frame(lng0: number, lat0: number) {
  const k = Math.cos((lat0 * Math.PI) / 180)
  return {
    toLocal: ([lng, lat]: [number, number]): [number, number] => [
      ((lng - lng0) * Math.PI / 180) * R * k,
      ((lat - lat0) * Math.PI / 180) * R,
    ],
    toWgs: ([x, y]: [number, number]): [number, number] => [round(lng0 + (x / (R * k)) * 180 / Math.PI), round(lat0 + (y / R) * 180 / Math.PI)],
  }
}

const closed = (r: Ring) => r.length >= 4 && r[0][0] === r.at(-1)![0] && r[0][1] === r.at(-1)![1]

/** Plan convex hull of the model, in local metres: for landmarks whose OSM element isn't an area. */
function hull(glb: Uint8Array): Array<[number, number]> {
  const { json, bin } = parseGlb(glb)
  const pts: Array<[number, number]> = []
  const data = new DataView(bin.buffer, bin.byteOffset, bin.byteLength)
  for (const prim of json.meshes[0].primitives) {
    const a = json.accessors[prim.attributes.POSITION], v = json.bufferViews[a.bufferView]
    for (let i = 0; i < a.count; i++) {
      const at = (v.byteOffset ?? 0) + i * 12
      pts.push([data.getFloat32(at, true), -data.getFloat32(at + 8, true)])
    }
  }
  pts.sort((p, q) => p[0] - q[0] || p[1] - q[1])
  const turn = (o: number[], a: number[], b: number[]) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
  const half = (list: Array<[number, number]>) => {
    const out: Array<[number, number]> = []
    for (const p of list) {
      while (out.length >= 2 && turn(out.at(-2)!, out.at(-1)!, p) <= 0) out.pop()
      out.push(p)
    }
    return out.slice(0, -1)
  }
  const ring = [...half(pts), ...half([...pts].reverse())]
  return [...ring, ring[0]]
}

function osmRecord(osm: Osm, ref: string) {
  const e = osm.get(ref)
  return { type: e.type, id: e.id, version: e.version, timestamp: e.timestamp, url: `https://www.openstreetmap.org/${ref}` }
}

export type SubmissionInput = {
  id: string
  landmark: CatalogLandmark
  model: string
  generator: string
  generatorUrl: string
  converted: Converted
  osmRefs: string[]
  osm: Osm
  notes: string[]
  references: Reference[]
}

export function submission(input: SubmissionInput) {
  const { id, landmark: l, converted: c, osm, osmRefs } = input
  const { toLocal, toWgs } = frame(l.lng, l.lat)
  const [first, ...rest] = osmRefs

  const rings = first ? osm.rings(first).filter(closed) : []
  const replacementFootprint: Polygonal = rings.length === 1
    ? { type: 'Polygon', coordinates: [rings[0].map(([x, y]) => [round(x), round(y)] as [number, number])] }
    : rings.length > 1
      ? { type: 'MultiPolygon', coordinates: rings.map((r) => [r.map(([x, y]) => [round(x), round(y)] as [number, number])]) }
      : { type: 'Polygon', coordinates: [hull(c.detail.glb).map(toWgs)] }
  const localFootprint: Polygonal = replacementFootprint.type === 'Polygon'
    ? { type: 'Polygon', coordinates: replacementFootprint.coordinates.map((r) => r.map(toLocal)) }
    : { type: 'MultiPolygon', coordinates: replacementFootprint.coordinates.map((p) => p.map((r) => r.map(toLocal))) }

  const bounds = (lod: Converted['detail']) => [
    [lod.min[0], -lod.max[2], lod.min[1]],
    [lod.max[0], -lod.min[2], lod.max[1]],
  ]
  const [dmin, dmax] = bounds(c.detail), [lmin, lmax] = bounds(c.low)
  const boundsBlenderM = [dmin.map((v, i) => Math.min(v, lmin[i])), dmax.map((v, i) => Math.max(v, lmax[i]))]
    .map((p) => p.map((v) => Math.round(v * 1000) / 1000))
  boundsBlenderM[0][2] = 0

  const exportNotes = [
    `Original procedural model from ${REPOSITORY} (catalog id "${l.id}", model "${input.model}"), generated by ${input.generatorUrl}. ` +
      `That repository is the editable source; source.blend.gz is the exported mesh imported into Blender for convenience.`,
    'Exported for Open Landmarks v1: placement bearing and scale baked in; moving parts frozen in their rest pose; ' +
      'footings and basements below the lowest ground (y = 0) cut away; material colours carried over exactly, as library finishes where they are not standard swatches.',
    ...(c.report.detachedM2 > 0.5
      ? [`Window panels clipped to the walls behind them; ${Math.round(c.report.detachedM2)} m² of glazing with no wall behind it (curtain walls, glazing past a wall's edge) uses the ${input.model}-glazing finish in the window colour.`]
      : []),
    ...(c.merged.length
      ? [`To fit six materials, folded ${c.merged.map((m) => `${m.from} into ${m.into} (ΔE ${m.deltaE})`).join(', ')}.`]
      : []),
  ]

  const asset = {
    id,
    name: l.name,
    anchor: [l.lng, l.lat],
    heading: 0,
    units: 'metres',
    axes: 'X east / Y up / Z south',
    minZoom: l.minzoom ?? 15,
    detailZoom: 17,
    lods: {
      low: { url: 'low.glb', bytes: c.low.glb.length, sha256: sha(c.low.glb) },
      detail: { url: 'detail.glb', bytes: c.detail.glb.length, sha256: sha(c.detail.glb) },
    },
    triangles: c.detail.triangles,
    boundsBlenderM,
    entranceLights: [],
    replacementFootprint,
    basemapReplacement: null,
    osm: osmRecord(osm, first),
    additionalOsm: rest.map((r) => osmRecord(osm, r)),
    ...(l.wikidata ? { wikidata: l.wikidata } : {}),
    rightsStatus: 'review-required',
    geometryStatus: 'draft',
    attribution: `Open Landmarks; contains © OpenStreetMap contributors, ODbL-1.0; model by ${AUTHOR} (${REPOSITORY}).`,
    references: input.references,
    modelSources: [],
    aliases: [],
    authors: [AUTHOR],
    artisticLicense: 'CC-BY-4.0',
    spatialDataLicense: 'ODbL-1.0',
    licenseScope: 'CC BY applies to original artistic contributions only; ODbL applies to OSM-derived spatial data. Reference photographs retain their own licenses.',
    assistance:
      `AI-assisted (Claude): the TypeScript generator ${input.generator} was written from the open evidence in the modelling notes ` +
      '(OSM, public lidar and aerials, licensed photographs, published dimensions), reviewed by a human against reference photos, and exported deterministically. No photographic textures.',
    review: { status: 'pending', reviewer: null, checks: {} },
    modelingNotes: [...input.notes, ...exportNotes],
    source: 'source.blend.gz',
    spatialSource: 'spatial-source.json',
    preview: 'preview.webp',
  }

  const local = (ref: string) => {
    const rs = osm.rings(ref)
    const e = osm.get(ref)
    if (e.type === 'node') return { type: 'Point', coordinates: toLocal([e.lon!, e.lat!]) }
    if (rs.length === 1) return closed(rs[0]) ? { type: 'Polygon', coordinates: [rs[0].map(toLocal)] } : { type: 'LineString', coordinates: rs[0].map(toLocal) }
    return { type: 'MultiPolygon', coordinates: rs.map((r) => [r.map(toLocal)]) }
  }
  const spatial = {
    id,
    anchor: [l.lng, l.lat],
    coordinateSystem: 'Local metres about the anchor (equirectangular, WGS84 radius): X east, Y north, Z up. glTF export: X east, Y up, Z south. Heading already baked.',
    license: 'ODbL-1.0',
    footprint: localFootprint,
    replacementFootprint,
    parts: osmRefs.map((ref) => {
      const e = osm.get(ref)
      return { osm: ref, tags: e.tags, geometry: local(ref), version: e.version, timestamp: e.timestamp }
    }),
    osm: asset.osm,
    additionalOsm: asset.additionalOsm,
    tags: osm.get(first).tags,
    ...(osmRefs.length === (l.replaces?.length ?? 0) ? {} : { note: 'This landmark replaces no mapped building; the OSM feature cited is the one that names it.' }),
  }
  return { asset, spatial }
}
