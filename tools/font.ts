/** Accents and typographic punctuation folded to the ASCII the font has. */
function ascii(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/[^\x20-\x7e]/g, '?')
}

/** Draw `text` with its top-left at (x, y), clipped to the bitmap. */
export function drawText(bmp: Bitmap, text: string, x: number, y: number, scale = 2, colour = [40, 40, 40]) {
  let cx = x
  for (const ch of ascii(text)) {
    const g = (ch.charCodeAt(0) - 32) * 5
    for (let col = 0; col < 5; col++) {
      const bits = GLYPHS[g + col]
      for (let row = 0; row < 8; row++) {
        if (!(bits & (1 << row))) continue
        for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
          const px = cx + col * scale + dx, py = y + row * scale + dy
          if (px < 0 || py < 0 || px >= bmp.w || py >= bmp.h) continue
          bmp.data.set([...colour, 255], (py * bmp.w + px) * 4)
        }
      }
    }
    cx += 6 * scale
  }
}
