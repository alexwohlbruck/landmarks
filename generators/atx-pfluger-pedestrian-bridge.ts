/** Corners moved in under the slab, onto the outer girder's line: the deck is always on the left of a ring. */
function inset(ring: number[][], d: number): P2[] {
  const n = ring.length
  return ring.map((p, i) => {
    const a = ring[(i + n - 1) % n], b = ring[(i + 1) % n]
    const e0 = nrm2(p[0] - a[0], p[1] - a[1]), e1 = nrm2(b[0] - p[0], b[1] - p[1])
    const l0: P2 = [-e0[1], e0[0]], l1: P2 = [-e1[1], e1[0]]
    const m = nrm2(l0[0] + l1[0], l0[1] + l1[1]), c = Math.max(0.5, m[0] * l1[0] + m[1] * l1[1])
    return [p[0] + (m[0] * d) / c, p[1] + (m[1] * d) / c]
  })
}

function inPoly(p: P2, poly: number[][]) {
  let c = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j]
    if ((yi > p[1]) !== (yj > p[1]) && p[0] < ((xj - xi) * (p[1] - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}
const onDeck = (p: P2) => inPoly(p, OUTER) && !inPoly(p, HOLE)

/** Distance from p along direction d to the deck's edge (outline or hole). */
function rayToEdge(p: P2, d: P2, cap = 14) {
  let best = cap
  for (const ring of [OUTER, HOLE]) for (let i = 0; i < ring.length; i++) {
    const a = ring[i], b = ring[(i + 1) % ring.length], ex = b[0] - a[0], ey = b[1] - a[1]
    const den = d[0] * ey - d[1] * ex
    if (Math.abs(den) < 1e-9) continue
    const t = ((a[0] - p[0]) * ey - (a[1] - p[1]) * ex) / den, u = ((a[0] - p[0]) * d[1] - (a[1] - p[1]) * d[0]) / den
    if (t > 0 && u >= 0 && u <= 1) best = Math.min(best, t)
  }
  return best
}

/** A point on a centre line at distance s, with its unit tangent and deck top. */
function along(name: string, s: number): { p: P2; t: P2; z: number } {
  const c = CHAINS[name]
  let acc = 0
  for (let i = 1; i < c.length; i++) {
    const l = Math.hypot(c[i][0] - c[i - 1][0], c[i][1] - c[i - 1][1])
    if (acc + l >= s || i === c.length - 1) {
      const f = Math.min(1, Math.max(0, (s - acc) / (l || 1)))
      return { p: [c[i - 1][0] + (c[i][0] - c[i - 1][0]) * f, c[i - 1][1] + (c[i][1] - c[i - 1][1]) * f], t: nrm2(c[i][0] - c[i - 1][0], c[i][1] - c[i - 1][1]), z: c[i - 1][2] + (c[i][2] - c[i - 1][2]) * f }
    }
    acc += l
  }
  throw new Error('along')
}
const chainLength = (name: string) => CHAINS[name].reduce((s, q, i, c) => (i ? s + Math.hypot(q[0] - c[i - 1][0], q[1] - c[i - 1][1]) : 0), 0)

/** Deck top at any point: the nearest centre line's (the helix excluded, which passes under the junction). */
function deckTop(p: P2, names = ['main', 'west', 'ext', 'link']) {
  let best = Infinity, z = 0
  for (const n of names) for (const q of CHAINS[n]) {
    const d = (q[0] - p[0]) ** 2 + (q[1] - p[1]) ** 2
    if (d < best) { best = d; z = q[2] }
  }
  return Math.max(z, ground(p[0], p[1]) + 0.12)
}

