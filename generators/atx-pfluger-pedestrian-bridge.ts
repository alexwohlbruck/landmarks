/** Ear clipping for one simple polygon, CCW; returns index triples. */
export function earclip(pts: P2[]): [number, number, number][] {
  const idx = pts.map((_, i) => i), out: [number, number, number][] = []
  const cross = (a: P2, b: P2, c: P2) => (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
  const inside = (p: P2, a: P2, b: P2, c: P2) => cross(a, b, p) >= -1e-9 && cross(b, c, p) >= -1e-9 && cross(c, a, p) >= -1e-9
  let guard = 0
  while (idx.length > 3 && guard++ < 100000) {
    let cut = false
    for (let k = 0; k < idx.length; k++) {
      const i0 = idx[(k + idx.length - 1) % idx.length], i1 = idx[k], i2 = idx[(k + 1) % idx.length]
      const [a, b, c] = [pts[i0], pts[i1], pts[i2]]
      if (cross(a, b, c) <= 1e-9) continue
      let ok = true
      for (const j of idx) {
        if (j === i0 || j === i1 || j === i2) continue
        const p = pts[j]
        if ((p[0] === a[0] && p[1] === a[1]) || (p[0] === b[0] && p[1] === b[1]) || (p[0] === c[0] && p[1] === c[1])) continue
        if (inside(p, a, b, c)) { ok = false; break }
      }
      if (!ok) continue
      out.push([i0, i1, i2]); idx.splice(k, 1); cut = true; break
    }
    if (!cut) throw new Error(`earclip stuck with ${idx.length} vertices`)
  }
  out.push([idx[0], idx[1], idx[2]])
  return out
}

const segX = (p: P2, q: P2, a: P2, b: P2) => {
  const d = (q[0] - p[0]) * (b[1] - a[1]) - (q[1] - p[1]) * (b[0] - a[0])
  if (Math.abs(d) < 1e-12) return false
  const t = ((a[0] - p[0]) * (b[1] - a[1]) - (a[1] - p[1]) * (b[0] - a[0])) / d
  const u = ((a[0] - p[0]) * (q[1] - p[1]) - (a[1] - p[1]) * (q[0] - p[0])) / d
  return t > 1e-6 && t < 1 - 1e-6 && u > 1e-6 && u < 1 - 1e-6
}

/** The deck outline and its hole as one simple polygon (the hole joined by a slit), with each corner's ring and index. */
function joined(): { pts: P2[]; ref: [number, number][] } {
  const o = OUTER.map((r) => [r[0], r[1]] as P2), h = HOLE.map((r) => [r[0], r[1]] as P2)
  const edges: [P2, P2][] = [...o.map((p, i) => [p, o[(i + 1) % o.length]] as [P2, P2]), ...h.map((p, i) => [p, h[(i + 1) % h.length]] as [P2, P2])]
  let best: [number, number, number] | undefined
  for (let j = 0; j < h.length; j++) for (let i = 0; i < o.length; i++) {
    const d = Math.hypot(o[i][0] - h[j][0], o[i][1] - h[j][1])
    if (best && d >= best[2]) continue
    if (edges.some(([a, b]) => segX(h[j], o[i], a, b))) continue
    best = [i, j, d]
  }
  if (!best) throw new Error('no bridge into the hole')
  const [bi, bj] = best, pts: P2[] = [], ref: [number, number][] = []
  for (let i = 0; i <= bi; i++) { pts.push(o[i]); ref.push([0, i]) }
  for (let k = 0; k <= h.length; k++) { const j = (bj + k) % h.length; pts.push(h[j]); ref.push([1, j]) }
  for (let i = bi; i < o.length; i++) { pts.push(o[i]); ref.push([0, i]) }
  return { pts, ref }
}

